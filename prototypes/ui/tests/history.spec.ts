import { test,expect } from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('history filters, details and dashboard share recorded focus',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await nav.getByRole('button',{name:'Histórico',exact:true}).click();
 const history=page.locator('.history-page');
 await expect(history.locator('.history-stat').first()).toContainText('10h 32min');
 await history.getByRole('button',{name:'Hoje',exact:true}).click();
 await expect(history.locator('.history-stat').first()).toContainText('2h 15min');
 await expect(history.locator('.history-session')).toHaveCount(5);
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Abrir filtros do histórico'}).click();
 await history.getByRole('combobox',{name:'Categoria do histórico'}).click();
 await page.getByRole('option',{name:'Leitura',exact:true}).click();
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
 await expect(history.locator('.history-session')).toHaveCount(1);
 await history.getByRole('button',{name:'Detalhes de Clean Architecture',exact:true}).click();
 await expect(page.getByRole('dialog')).toContainText('30 min');
 await page.keyboard.press('Escape');
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Abrir filtros do histórico'}).click();
 await history.getByRole('combobox',{name:'Categoria do histórico'}).click();
 await page.getByRole('option',{name:'Todas',exact:true}).click();
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Abrir filtros do histórico'}).click();
 await history.getByRole('combobox',{name:'Status do histórico'}).click();
 await page.getByRole('option',{name:'Interrompidas',exact:true}).click();
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
 await expect(history.getByText('Nenhuma sessão encontrada')).toBeVisible();
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Abrir filtros do histórico'}).click();
 await history.getByRole('combobox',{name:'Status do histórico'}).click();
 await page.getByRole('option',{name:'Todos',exact:true}).click();
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
 await page.screenshot({path:info.outputPath('history-today.png'),animations:'disabled',scale:'css'});
 await history.getByRole('button',{name:'30 dias',exact:true}).click();
 await expect(history.locator('.history-bar-column')).toHaveCount(30);
 await history.getByRole('button',{name:'Mostrar mais sessões',exact:true}).click();
 await expect(history.locator('.history-session')).toHaveCount(16);
 await page.screenshot({path:info.outputPath('history-month.png'),animations:'disabled',scale:'css'});
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await page.clock.install();
 await page.getByRole('button',{name:'Iniciar foco',exact:true}).click();
 await page.clock.fastForward(1500*1000+250);
 await expect(page.locator('[data-widget=goal]')).toContainText('2h 40min');
 await nav.getByRole('button',{name:'Histórico',exact:true}).click();
 await history.getByRole('button',{name:'Hoje',exact:true}).click();
 await expect(history.locator('.history-session')).toHaveCount(6);
 await expect(history.locator('.history-session').first()).toContainText('Sessão local');
 await expect(history.locator('.history-stat').first()).toContainText('2h 40min');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
});
test('appearance preference persists and system motion is respected',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await nav.getByRole('button',{name:info.project.name==='mobile'?'Ajustes':'Configurações',exact:true}).click();
 await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Aparência',exact:true}).click();
 await page.getByRole('button',{name:'Escuro',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.getByRole('switch',{name:'Reduzir animações'}).click();
 await expect(page.locator('html')).toHaveAttribute('data-motion','reduced');
 await page.screenshot({path:info.outputPath('settings-dark.png'),animations:'disabled',scale:'css'});
 await page.reload();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await expect(page.locator('html')).toHaveAttribute('data-motion','reduced');
 await page.screenshot({path:info.outputPath('dashboard-dark.png'),animations:'disabled',scale:'css'});
 await nav.getByRole('button',{name:info.project.name==='mobile'?'Ajustes':'Configurações',exact:true}).click();
 await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Aparência',exact:true}).click();
 await page.getByRole('button',{name:'Sistema',exact:true}).click();
 await page.emulateMedia({colorScheme:'light'});
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
});

test('interrupted focus is logged, pauses are excluded and reset discards time',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await page.clock.install();
 await page.getByRole('button',{name:'Abrir sessão de foco',exact:true}).click();
 await page.getByRole('button',{name:'Iniciar',exact:true}).click();
 await page.clock.fastForward(70000);
 await page.getByRole('button',{name:'Encerrar',exact:true}).click();
 await page.getByRole('button',{name:'Iniciar',exact:true}).click();
 await page.clock.fastForward(15000);
 await page.getByRole('button',{name:'Reiniciar',exact:true}).click();
 await page.getByRole('button',{name:'Voltar',exact:true}).click();
 await nav.getByRole('button',{name:'Histórico',exact:true}).click();
 const history=page.locator('.history-page');
 await history.getByRole('button',{name:'Hoje',exact:true}).click();
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Abrir filtros do histórico'}).click();
 await history.getByRole('combobox',{name:'Status do histórico'}).click();
 await page.getByRole('option',{name:'Interrompidas',exact:true}).click();
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
 await expect(history.locator('.history-session')).toHaveCount(1);
 await expect(history.locator('.history-session').first()).toContainText('1 min');
 await expect(history.locator('.history-session').first()).toContainText('Interrompida');
});
