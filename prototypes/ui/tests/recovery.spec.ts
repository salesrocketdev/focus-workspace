import { openNavigation } from '../navigate-test';
import {test,expect} from '@playwright/test';
const key='focus-workspace:v4:workspace';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('active and paused timers restore after reload; expiry logs once',async({page},info)=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Iniciar foco',exact:true}).click();
 await expect.poll(()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).timer.running,key)).toBe(true);
 await page.evaluate(k=>{const v=JSON.parse(localStorage.getItem(k)!);v.timer.startedAt=Date.now()-120000;localStorage.setItem(k,JSON.stringify(v))},key);
 await page.reload();
 await expect(page.getByRole('button',{name:'Pausar foco',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pausar foco',exact:true}).click();
 const paused=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).timer,key);
 expect(paused.seconds).toBeGreaterThan(1370);expect(paused.seconds).toBeLessThanOrEqual(1380);
 await page.reload();
 expect(await page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).timer.seconds,key)).toBe(paused.seconds);
 await page.getByRole('button',{name:'Iniciar foco',exact:true}).click();
 await page.evaluate(k=>{const v=JSON.parse(localStorage.getItem(k)!);v.timer.startedAt=Date.now()-1600000;localStorage.setItem(k,JSON.stringify(v))},key);
 await page.reload();
 await expect.poll(()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).timer.phase,key)).toBe('short');
 await expect.poll(()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)!).records.filter((r:{origin:string})=>r.origin==='session').length,key)).toBe(1);
 await page.reload();
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,'Histórico');
 await page.locator('.history-page').getByRole('button',{name:'Hoje',exact:true}).click();
 await expect(page.locator('.history-session')).toHaveCount(6);
 await expect(page.locator('.history-stat').first()).toContainText('2h 40min');
});
test('wake lock is opt-in and released when paused',async({page},info)=>{
 await page.addInitScript(()=>{let requests=0,releases=0;Object.defineProperty(window,'wakeDemo',{get:()=>({requests,releases})});Object.defineProperty(navigator,'wakeLock',{configurable:true,value:{request:async()=>{requests++;const sentinel=new EventTarget() as EventTarget&{released:boolean;release:()=>Promise<void>};sentinel.released=false;sentinel.release=async()=>{if(!sentinel.released){sentinel.released=true;releases++;sentinel.dispatchEvent(new Event('release'))}};return sentinel}}})});
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,info.project.name==='mobile'?'Ajustes':'Configurações');
 if(info.project.name==='mobile')await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Sessões de foco',exact:true}).click();
 await page.getByRole('switch',{name:'Manter tela ligada'}).click();
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await page.getByRole('button',{name:'Iniciar foco',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>(window as unknown as {wakeDemo:{requests:number}}).wakeDemo.requests)).toBeGreaterThan(0);
 await page.getByRole('button',{name:'Pausar foco',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>(window as unknown as {wakeDemo:{releases:number}}).wakeDemo.releases)).toBeGreaterThan(0);
});
