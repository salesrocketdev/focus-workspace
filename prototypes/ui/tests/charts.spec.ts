import { openNavigation } from '../navigate-test';
import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('interactive analytics use filtered data and support keyboard and touch',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,'Histórico');
 const history=page.locator('.history-page');
 const points=history.getByRole('group',{name:'Tempo de foco por dia'});
 const detail=history.getByRole('status',{name:'Detalhes do dia'});
 await expect(points.getByRole('button')).toHaveCount(7);
 await expect(detail).toContainText('2h 15min');
 await expect(detail).toContainText('5 sessões');
 await history.getByRole('button',{name:'Dia anterior no gráfico'}).click();
 await expect(detail).toContainText('1h 42min');
 await points.getByRole('button').last().focus();
 await page.keyboard.press('ArrowLeft');
 await expect(detail).toContainText('1h 42min');
 await history.getByRole('button',{name:'Linha',exact:true}).click();
 await expect(history.locator('.chart-line')).toBeVisible();
 await history.getByRole('button',{name:'Barras',exact:true}).click();
 await expect(history.locator('.chart-line')).toHaveCount(0);
 await history.getByRole('button',{name:'Hoje',exact:true}).click();
 const legend=history.getByRole('group',{name:'Categorias do gráfico'});
 await legend.getByRole('button',{name:/Leitura/}).click();
 await expect(history.getByRole('status',{name:'Detalhes da categoria'})).toContainText('30 min');
 await history.getByRole('button',{name:/da meta diária. Ver detalhes/}).click();
 await expect(history.locator('.goal-tooltip')).toContainText('Realizado: 2h 15min');
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Abrir filtros do histórico'}).click();
 await history.getByRole('combobox',{name:'Categoria do histórico'}).click();
 await page.getByRole('option',{name:'Leitura',exact:true}).click();
 if(info.project.name==='mobile')await history.getByRole('button',{name:'Aplicar filtros',exact:true}).click();
 await expect(detail).toContainText('30 min');
 await expect(detail).toContainText('1 sessão');
 await expect(history.getByRole('status',{name:'Detalhes da categoria'})).toContainText('100%');
 await expect(history.locator('.goal-tooltip')).toContainText('Realizado: 2h 15min');
 await page.screenshot({path:info.outputPath('interactive-history.png'),animations:'disabled',scale:'css'});
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 const summary=page.getByRole('group',{name:'Resumo de foco dos últimos dias'});
 await summary.getByRole('button').last().click();
 await expect(page.locator('[data-widget=summary]')).toContainText('29/01 · 2h 15min');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
});
