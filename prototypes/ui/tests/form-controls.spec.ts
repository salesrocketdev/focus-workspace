import { openNavigation } from '../navigate-test';
import { test,expect } from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('custom select supports pointer, keyboard and top layer in a dialog',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,info.project.name==='mobile'?'Ajustes':'Configurações');
 if(info.project.name==='mobile')await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Sessões de foco',exact:true}).click();
 const select=page.getByRole('combobox',{name:'Duração do Pomodoro'});
 await select.focus();await page.keyboard.press('ArrowDown');
 await expect(select).toHaveAttribute('aria-expanded','true');
 await expect(page.getByRole('listbox')).toBeVisible();
 await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
 await expect(select).toHaveText('30 minutos');
 await select.click();await page.keyboard.press('Escape');await expect(select).toHaveAttribute('aria-expanded','false');await expect(select).toBeFocused();
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await page.getByRole('button',{name:'Abrir sessão de foco',exact:true}).click();
 await page.getByRole('button',{name:'Configurar sessão de foco',exact:true}).click();
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('combobox',{name:'Pausa curta'}).click();
 await expect(page.getByRole('listbox')).toBeVisible();
 await page.screenshot({path:info.outputPath('custom-select-dialog.png'),animations:'disabled',scale:'css'});
 await page.keyboard.press('Escape');await expect(dialog).toBeVisible();await expect(page.getByRole('listbox')).toHaveCount(0);
 await dialog.getByRole('combobox',{name:'Pausa curta'}).click();await page.getByRole('option',{name:'10 minutos',exact:true}).click();
 await expect(dialog.getByRole('combobox',{name:'Pausa curta'})).toHaveText('10 minutos');
});
test('toggle cards persist and search fields can be cleared',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,info.project.name==='mobile'?'Ajustes':'Configurações');
 if(info.project.name==='mobile')await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Sessões de foco',exact:true}).click();
 const toggle=page.getByRole('switch',{name:'Iniciar pausas automaticamente'});
 await expect(toggle).toHaveAttribute('aria-checked','false');
 await toggle.focus();await page.keyboard.press('Space');await expect(toggle).toHaveAttribute('aria-checked','true');
 await page.screenshot({path:info.outputPath('toggle-cards-light.png'),animations:'disabled',scale:'css'});
 if(info.project.name==='mobile')await page.getByRole('button',{name:'Voltar às configurações'}).click();
 await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Aparência',exact:true}).click();
 await page.getByRole('button',{name:'Escuro',exact:true}).click();
 await page.screenshot({path:info.outputPath('toggle-cards-dark.png'),animations:'disabled',scale:'css'});
 await page.reload();await openNavigation(nav,info.project.name==='mobile'?'Ajustes':'Configurações');
 if(info.project.name==='mobile')await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Sessões de foco',exact:true}).click();
 await expect(toggle).toHaveAttribute('aria-checked','true');
 await openNavigation(nav,'Biblioteca');
 const search=page.getByRole('searchbox',{name:'Buscar na biblioteca'});
 await search.fill('exemplo');await page.getByRole('button',{name:'Limpar buscar na biblioteca'}).click();
 await expect(search).toHaveValue('');await expect(search).toBeFocused();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
});
