import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('settings section navigation and notification center',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await nav.getByRole('button',{name:info.project.name==='mobile'?'Ajustes':'Configurações',exact:true}).click();
 const sections=page.getByRole('navigation',{name:'Seções de configurações'});
 await expect(sections.getByRole('button',{name:'Sessões de foco'})).toHaveAttribute('aria-current','page');
 await expect(page.getByRole('combobox',{name:'Duração do Pomodoro'})).toBeVisible();
 await sections.getByRole('button',{name:'Notificações',exact:true}).click();
 await expect(page.getByRole('combobox',{name:'Duração do Pomodoro'})).toHaveCount(0);
 await expect(page.getByRole('switch',{name:'Fim do período de foco'})).toHaveAttribute('aria-checked','true');
 await page.getByRole('button',{name:'Enviar notificação de teste'}).click();
 await page.screenshot({path:info.outputPath('settings-notifications.png'),animations:'disabled',scale:'css'});
 await page.getByRole('button',{name:'Abrir notificações'}).click();
 const dialog=page.getByRole('dialog',{name:'Notificações'});
 await expect(dialog).toContainText('Notificação de teste');
 await dialog.getByRole('button',{name:'Marcar todas como lidas'}).click();
 await expect(dialog).toContainText('0 não lida(s)');
 await dialog.getByRole('button',{name:'Fechar',exact:true}).click();
 await page.reload();
 await page.getByRole('button',{name:'Abrir notificações'}).click();
 await expect(dialog).toContainText('Notificação de teste');
 await dialog.getByRole('button',{name:'Preferências',exact:true}).click();
 await expect(sections.getByRole('button',{name:'Notificações',exact:true})).toHaveAttribute('aria-current','page');
 await page.getByRole('switch',{name:'Fim do período de foco'}).click();
 await sections.getByRole('button',{name:'Sessões de foco'}).click();
 await page.getByRole('combobox',{name:'Duração do Pomodoro'}).click();
 await page.getByRole('option',{name:'1 minuto',exact:true}).click();
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await page.clock.install();
 await page.getByRole('button',{name:'Iniciar foco',exact:true}).click();
 await page.clock.fastForward(61000);
 await page.getByRole('button',{name:'Abrir notificações'}).click();
 await expect(dialog).not.toContainText('Sessão de foco concluída');
 await dialog.getByRole('button',{name:'Limpar notificações'}).click();
 await expect(dialog).toContainText('Nenhum aviso por aqui');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
});
test('PWA manifest and notification worker are served',async({page,request})=>{
 await page.goto('/');
 const manifest=await request.get('/manifest.webmanifest');expect(manifest.ok()).toBeTruthy();
 const data=await manifest.json();expect(data.display).toBe('standalone');
 for(const icon of data.icons){const response=await request.get('/'+icon.src);expect(response.ok()).toBeTruthy();expect(response.headers()['content-type']).toContain('image/png')}
 const state=await page.evaluate(async()=>{const reg=await navigator.serviceWorker.register('/sw.js');await navigator.serviceWorker.ready;return reg.scope});
 expect(state).toContain('127.0.0.1:4173');
});
