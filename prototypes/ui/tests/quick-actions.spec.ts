import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('compact timer shares session across navigation and can be closed without stopping',async({page},info)=>{
 await page.goto('/');
 await page.clock.install();
 await page.getByRole('button',{name:'Abrir sessão de foco',exact:true}).click();
 await page.getByRole('button',{name:'Abrir foco compacto',exact:true}).click();
 const mini=page.getByRole('region',{name:'Foco compacto'});
 await expect(mini).toBeVisible();
 await mini.getByRole('button',{name:'Iniciar foco compacto'}).click();
 await page.clock.fastForward(10000);
 await expect(mini.getByRole('img',{name:'Tempo compacto: 24:50'})).toBeVisible();
 await expect(page.getByRole('img',{name:'24:50 · Leitura'})).toBeVisible();
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await nav.getByRole('button',{name:'Agenda',exact:true}).click();
 await expect(mini).toBeVisible();
 await page.screenshot({path:info.outputPath('compact-focus.png'),animations:'disabled',scale:'css'});
 await mini.getByRole('button',{name:'Fechar foco compacto'}).click();
 await expect(mini).toHaveCount(0);
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await expect(page.getByRole('button',{name:'Pausar foco',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pausar foco',exact:true}).click();
});
test('quick actions search and keyboard navigation do not discard panel edits',async({page},info)=>{
 await page.goto('/');
 await page.keyboard.press('Control+k');
 const dialog=page.getByRole('dialog',{name:'Ações rápidas'});
 await expect(dialog).toBeVisible();
 await dialog.getByRole('searchbox',{name:'Buscar ações'}).fill('historico');
 await expect(dialog.locator('.command-item')).toHaveCount(1);
 await page.keyboard.press('Enter');
 await expect(page.getByRole('heading',{name:'Histórico',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Abrir ações rápidas'}).click();
 await dialog.getByRole('searchbox',{name:'Buscar ações'}).fill('zzzz');
 await expect(dialog.getByText('Nenhuma ação encontrada')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(dialog).toHaveCount(0);
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await page.getByRole('button',{name:'Editar painel',exact:true}).click();
 await page.keyboard.press('Control+k');
 await expect(dialog).toBeVisible();
 await expect(dialog.getByRole('button',{name:/Abrir Agenda/})).toHaveCount(0);
 await page.keyboard.press('Escape');
 await expect(page.getByRole('button',{name:'Salvar painel',exact:true})).toBeVisible();
});
