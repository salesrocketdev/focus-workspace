import { openNavigation } from '../navigate-test';
import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('presets apply shared preferences and picker changes context safely',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,info.project.name==='mobile'?'Ajustes':'Configurações');
 if(info.project.name==='mobile')await page.getByRole('navigation',{name:'Seções de configurações'}).getByRole('button',{name:'Sessões de foco',exact:true}).click();
 const deep=page.getByRole('button',{name:/Foco profundo/});
 await deep.click();
 await expect(deep).toHaveAttribute('aria-pressed','true');
 await expect(page.getByRole('combobox',{name:'Duração do Pomodoro'})).toHaveText('50 minutos');
 await expect(page.getByRole('combobox',{name:'Pausa curta'})).toHaveText('10 minutos');
 await page.screenshot({path:info.outputPath('focus-presets.png'),animations:'disabled',scale:'css'});
 await nav.getByRole('button',{name:'Hoje',exact:true}).click();
 await page.getByRole('button',{name:'Abrir sessão de foco',exact:true}).click();
 const picker=page.getByRole('button',{name:'Escolher atividade',exact:true});
 await picker.click();
 const dialog=page.getByRole('dialog',{name:'Escolher atividade'});
 await dialog.getByRole('searchbox',{name:'Buscar atividade de foco'}).fill('habitos');
 await dialog.getByRole('button',{name:'Hábitos Atômicos',exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.locator('.focus-context-picker')).toContainText('Hábitos Atômicos');
 await expect(page.getByRole('img',{name:'50:00 · Leitura',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Iniciar',exact:true}).click();
 await expect(picker).toHaveCount(0);
 await page.getByRole('button',{name:'Controles',exact:true}).click();
 await expect(picker).toBeDisabled();
 await page.getByRole('button',{name:'Reiniciar',exact:true}).click();
 if(await page.getByRole('dialog',{name:'Descartar sessão atual?'}).isVisible())await page.getByRole('button',{name:'Descartar e reiniciar',exact:true}).click();
 await expect(picker).toBeEnabled();
 await picker.click();
 await dialog.getByRole('searchbox',{name:'Buscar atividade de foco'}).fill('estudos');
 await dialog.getByRole('button',{name:'Estudos',exact:true}).click();
 await expect(page.locator('.focus-context-picker')).toContainText('Estudos');
});
