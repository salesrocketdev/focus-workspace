import { test,expect } from '@playwright/test';
// Existing route tests explicitly skip first-run onboarding.
test.beforeEach(async({page})=>{await page.addInitScript(()=>{if(!localStorage.getItem('focus-workspace:v4:onboarding'))localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest'))})});

test('calendar supports day week month, navigation, source filters and event details',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await nav.getByRole('button',{name:'Agenda',exact:true}).click();
 const calendar=page.locator('.calendar-page');
 const rows=calendar.locator('.calendar-event-list .calendar-event');
 await expect(rows).toHaveCount(3);
 await page.screenshot({path:info.outputPath('calendar-day.png'),animations:'disabled',scale:'css'});
 const outlook=calendar.getByRole('button',{name:'Microsoft Outlook',exact:true});
 await outlook.click();await expect(outlook).toHaveAttribute('aria-pressed','false');
 await expect(rows).toHaveCount(2);
 await expect(calendar.locator('.calendar-slots')).toContainText('09:30 – 11:00');
 await outlook.click();await expect(outlook).toHaveAttribute('aria-pressed','true');
 const event=rows.filter({hasText:'Alinhamento de sprint'});
 await event.click();
 const dialog=page.getByRole('dialog',{name:'Alinhamento de sprint'});
 await expect(dialog).toContainText('11:00 – 11:45');
 await page.keyboard.press('Escape');
 await expect(dialog).toHaveCount(0);
 await expect(event).toBeFocused();
 await calendar.getByRole('button',{name:'Semana',exact:true}).click();
 await expect(calendar.locator('.calendar-week-column')).toHaveCount(7);
 await page.screenshot({path:info.outputPath('calendar-week.png'),animations:'disabled',scale:'css'});
 await calendar.locator('.calendar-week-day').filter({hasText:'30'}).click();
 await expect(rows).toHaveCount(2);
 await calendar.getByRole('button',{name:'Mês',exact:true}).click();
 await expect(calendar.locator('.calendar-month-day')).toHaveCount(42);
 await page.screenshot({path:info.outputPath('calendar-month.png'),animations:'disabled',scale:'css'});
 await calendar.getByRole('button',{name:'Próximo período'}).click();
 await expect(calendar.locator('.calendar-period')).toContainText('fevereiro');
 await calendar.getByRole('button',{name:'Hoje (demo)',exact:true}).click();
 await expect(calendar.locator('.calendar-period')).toContainText('janeiro');
 await calendar.getByRole('button',{name:'Dia',exact:true}).click();
 await expect(rows).toHaveCount(3);
 await calendar.getByRole('button',{name:'Próximo período'}).click();
 await expect(rows).toHaveCount(2);
 await calendar.getByRole('button',{name:'Próximo período'}).click();
 await calendar.getByRole('button',{name:'Próximo período'}).click();
 await expect(calendar.getByText('Nenhum compromisso visível')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBeTruthy();
});
