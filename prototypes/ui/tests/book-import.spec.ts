import { openNavigation } from '../navigate-test';
import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.addInitScript(()=>localStorage.setItem('focus-workspace:v4:onboarding',JSON.stringify('guest')))});
test('mock book search imports edition, chapters and shared reading context',async({page},info)=>{
 await page.goto('/');
 const nav=page.locator(info.project.name==='mobile'?'.bottom-nav':'.sidebar nav');
 await openNavigation(nav,'Atividades');
 await page.getByRole('button',{name:'Leituras',exact:true}).click();
 await page.getByRole('button',{name:'Buscar livro',exact:true}).click();
 const sheet=page.getByRole('dialog',{name:'Buscar livro'});
 await sheet.getByRole('searchbox',{name:'Título, autor ou ISBN'}).fill('aprender');
 await sheet.getByRole('button',{name:'Buscar',exact:true}).click();
 await expect(sheet.locator('.book-import-result')).toHaveCount(1);
 await sheet.getByRole('button',{name:'Selecionar Aprender com intenção — Português'}).click();
 await expect(sheet.getByLabel('Total de páginas')).toHaveValue('240');
 await page.screenshot({path:info.outputPath('book-import-edition.png'),animations:'disabled'});
 await sheet.getByRole('button',{name:'Importar livro',exact:true}).click();
 const book=page.locator('.activity-book').filter({hasText:'Aprender com intenção'});
 await expect(book).toBeVisible();
 await book.getByRole('button',{name:'Detalhes de Aprender com intenção'}).click();
 const detail=page.getByRole('dialog',{name:'Detalhes do livro'});
 await detail.getByRole('checkbox',{name:'Preparar o ambiente'}).check();
 await expect(detail.getByText('1 de 5 capítulos concluídos')).toBeVisible();
 await expect(detail.getByText('Pág. 0 de 240 · 0%')).toBeVisible();
 await detail.getByLabel('Novo capítulo').fill('Revisão extra');
 await detail.getByRole('button',{name:'Adicionar',exact:true}).click();
 await expect(detail.getByText('1 de 6 capítulos concluídos')).toBeVisible();
 await page.screenshot({path:info.outputPath('book-chapter-plan.png'),animations:'disabled'});
 await detail.getByRole('button',{name:'Concluir',exact:true}).click();
 await page.getByRole('button',{name:'Buscar livro',exact:true}).click();
 await expect(sheet.getByRole('button',{name:'Selecionar Aprender com intenção — Português'})).toBeDisabled();
 await sheet.getByRole('searchbox').fill('xyzabc');
 await sheet.getByRole('button',{name:'Buscar',exact:true}).click();
 await expect(sheet.getByText('Nenhum livro encontrado')).toBeVisible();
 await sheet.getByRole('searchbox').fill('9780000000026');
 await sheet.getByRole('button',{name:'Buscar',exact:true}).click();
 await sheet.getByRole('button',{name:'Selecionar O tempo de uma ideia — Português'}).click();
 await expect(sheet.getByLabel('Total de páginas')).toHaveValue('');
 await expect(sheet.getByText(/Sumário indisponível/)).toBeVisible();
 await sheet.getByLabel('Total de páginas').fill('180');
 await sheet.getByRole('button',{name:'Importar livro',exact:true}).click();
 await book.getByRole('button',{name:'Iniciar leitura'}).click();
 await expect(page.locator('.book-panel h2')).toHaveText('Aprender com intenção');
});
